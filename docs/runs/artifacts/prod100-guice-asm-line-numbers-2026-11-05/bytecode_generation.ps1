# Scratch of the C5f investigation: which classes does Guice generate with ASM while the real eqasim injector is built,
# and which ASM classes are loaded, on the old and the new class path (JVM option -Xlog:class+load).
# Needs the class path files and the compiled scratch harness of ab.ps1 (the argument files args-before/after.txt).
$ErrorActionPreference = "Continue"
$sc = "C:\Users\bienzeisler\AppData\Local\Temp\c5f"
$ab = "$sc\ab"
$jdk = "C:\Program Files\Eclipse Adoptium\jdk-25.0.4.101-hotspot"
foreach ($state in "before", "after") {
    $log = "$ab\classload-$state.txt"
    & "$jdk\bin\java.exe" "@$ab\args-$state.txt" "-Xlog:class+load:file=$log" org.eqasim.mode_choice.C5fBindings 2>&1 |
        Select-String "C5F_" | ForEach-Object { "{0,-6} {1}" -f $state, $_.Line }
    $generated = @(Select-String -Path $log -Pattern "ByGuice" | ForEach-Object { $_.Line })
    $kinds = $generated | ForEach-Object {
        if ($_ -match 'FastClassByGuice') { 'FastClassByGuice' } elseif ($_ -match 'DefineAccessByGuice') { 'DefineAccessByGuice' } else { 'other' }
    } | Group-Object | ForEach-Object { "$($_.Name)=$($_.Count)" }
    "{0,-6} classes loaded in total: {1}; generated by Guice: {2} ({3})" -f $state, (Get-Content $log | Measure-Object).Count, $generated.Count, ($kinds -join ", ")
    "{0,-6} plain org.objectweb.asm classes loaded: {1}; embedded com.google.inject.internal.asm classes loaded: {2}" -f $state,
        (Select-String -Path $log -Pattern " org.objectweb.asm" | Measure-Object).Count,
        (Select-String -Path $log -Pattern "com.google.inject.internal.asm" | Measure-Object).Count
    "{0,-6} LineNumbers loaded from: {1}" -f $state, ((Select-String -Path $log -Pattern "com.google.inject.internal.util.LineNumbers source:" | Select-Object -First 1).Line -replace '^.*source: ', '')
}
