HEADER_FILL = PatternFill("solid", fgColor="1F3864")
HEADER_FONT = Font(color="FFFFFF", bold=True, size=10)
BODY_FONT = Font(size=10)
TITLE_FONT = Font(bold=True, size=13, color="1F3864")
SECTION_FONT = Font(bold=True, size=11, color="1F3864")
BAND_FILL = PatternFill("solid", fgColor="EDF1F8")
THIN = Side(style="thin", color="BFC9DA")
CELL_BORDER = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)

RELEVANCE_FILLS = {
    "hoch": PatternFill("solid", fgColor="C6E0B4"),
    "mittel": PatternFill("solid", fgColor="FFE699"),
    "gering": PatternFill("solid", fgColor="F2F2F2"),
}
SHARING_FILLS = {
    "ja": PatternFill("solid", fgColor="C6E0B4"),
    "nein": PatternFill("solid", fgColor="F8CBAD"),
}


def _git_commit() -> str:
    """Return the current short commit hash, or a marker when unavailable."""
    try:
        result = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            capture_output=True, text=True, timeout=10, check=True,
        )
        return result.stdout.strip()
    except (subprocess.SubprocessError, OSError, FileNotFoundError):
        return "nicht ermittelbar"


def _write_inventory_sheet(sheet: Worksheet) -> None:
    """Write the inventory table with header formatting, banding and filters."""
    for column_index, (_key, header, width, _wrap) in enumerate(COLUMNS, start=1):
        cell = sheet.cell(row=1, column=column_index, value=header)
        cell.fill = HEADER_FILL
        cell.font = HEADER_FONT
        cell.alignment = Alignment(vertical="center", wrap_text=True)
        cell.border = CELL_BORDER
        sheet.column_dimensions[get_column_letter(column_index)].width = width
    sheet.row_dimensions[1].height = 34

    for row_offset, row in enumerate(ROWS):
        row_index = row_offset + 2
        banded = row_offset % 2 == 1
        for column_index, (key, _header, _width, wrap) in enumerate(COLUMNS, start=1):
            value = row.get(key, "")
            if key not in row:
                logger.warning("Zeile %s: Spalte '%s' fehlt", row.get("id", "?"), key)
            cell = sheet.cell(row=row_index, column=column_index, value=value)
            cell.font = BODY_FONT
            cell.alignment = Alignment(vertical="top", wrap_text=wrap)
            cell.border = CELL_BORDER
            if banded:
                cell.fill = BAND_FILL
            if key == "visum_relevanz" and value in RELEVANCE_FILLS:
                cell.fill = RELEVANCE_FILLS[value]
            if key == "weitergabe" and value in SHARING_FILLS:
                cell.fill = SHARING_FILLS[value]

    sheet.freeze_panes = "D2"
    sheet.auto_filter.ref = f"A1:{get_column_letter(len(COLUMNS))}{len(ROWS) + 1}"
    sheet.sheet_view.zoomScale = 90


def _write_legend_sheet(sheet: Worksheet) -> None:
    """Write the column dictionary."""
    sheet["A1"] = "Legende – Spaltendefinitionen"
    sheet["A1"].font = TITLE_FONT
    sheet.column_dimensions["A"].width = 34
    sheet.column_dimensions["B"].width = 118

    header_row = 3
    for column_index, header in enumerate(("Spalte", "Bedeutung"), start=1):
        cell = sheet.cell(row=header_row, column=column_index, value=header)
        cell.fill = HEADER_FILL
        cell.font = HEADER_FONT
        cell.alignment = Alignment(vertical="center")
        cell.border = CELL_BORDER

    for offset, (column_name, meaning) in enumerate(LEGEND_ROWS):
        row_index = header_row + 1 + offset
        name_cell = sheet.cell(row=row_index, column=1, value=column_name)
        meaning_cell = sheet.cell(row=row_index, column=2, value=meaning)
        for cell in (name_cell, meaning_cell):
            cell.font = BODY_FONT
            cell.alignment = Alignment(vertical="top", wrap_text=True)
            cell.border = CELL_BORDER
            if offset % 2 == 1:
                cell.fill = BAND_FILL
        name_cell.font = Font(size=10, bold=True)


def _write_notes_sheet(sheet: Worksheet, commit: str, generated_on: str) -> None:
    """Write scope, provenance and data-protection notes."""
    sheet["A1"] = "eqasim-BS – Datenquellen-Inventar"
    sheet["A1"].font = TITLE_FONT
    sheet.column_dimensions["A"].width = 140

    row_index = 3
    provenance = [
        f"Erzeugt am: {generated_on}",
        f"Repository-Stand (Git-Commit): {commit}",
        "Erzeugt mit: scripts/export_data_source_inventory.py (im Repository; erneut ausführbar)",
        f"Anzahl Einträge: {len(ROWS)}",
    ]
    for line in provenance:
        cell = sheet.cell(row=row_index, column=1, value=line)
        cell.font = BODY_FONT
        row_index += 1
    row_index += 1

    for title, lines in NOTES_BLOCKS:
        title_cell = sheet.cell(row=row_index, column=1, value=title)
        title_cell.font = SECTION_FONT
        row_index += 1
        for line in lines:
            cell = sheet.cell(row=row_index, column=1, value="•  " + line)
            cell.font = BODY_FONT
            cell.alignment = Alignment(vertical="top", wrap_text=True)
            sheet.row_dimensions[row_index].height = max(15, 13 * (1 + len(line) // 120))
            row_index += 1
        row_index += 1


def build_workbook(output_path: Path) -> Path:
    """Build the workbook and write it to ``output_path``.

    Creates the parent directory if it does not exist. An existing file is
    overwritten -- the workbook is fully regenerated from this module, so
    overwriting never loses hand-made content.
    """
    generated_on = dt.date.today().isoformat()
    commit = _git_commit()

    workbook = Workbook()
    inventory_sheet = workbook.active
    inventory_sheet.title = "Datenquellen"
    _write_inventory_sheet(inventory_sheet)
    _write_legend_sheet(workbook.create_sheet("Legende"))
    _write_notes_sheet(workbook.create_sheet("Hinweise"), commit, generated_on)

    output_path.parent.mkdir(parents=True, exist_ok=True)
    workbook.save(output_path)
    logger.info(
        "Datenquellen-Inventar geschrieben: %s (%d Einträge, %d Spalten, Commit %s)",
        output_path, len(ROWS), len(COLUMNS), commit,
    )
    return output_path


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--out", type=Path, default=DEFAULT_OUTPUT_PATH,
        help=f"Zielpfad der Excel-Datei (Standard: {DEFAULT_OUTPUT_PATH})",
    )
    arguments = parser.parse_args()
    build_workbook(arguments.out)


if __name__ == "__main__":
    main()
