"""Backtest the Wolfsburg rules for the per-Kreis control targets (ADR-0205).

SrV 2023 does not survey Wolfsburg (03103), so its row of every SrV-based Kreis target needs a
rule. This script measures how well each candidate rule predicts the seven Kreise SrV DID
survey: for every SrV Kreis k it treats k as unsurveyed, predicts k's SrV value and scores the
prediction against that value.

Predictions:
  copy        the anchor's SrV value (the rule Wolfsburg's SrV-only targets used before ADR-0205)
  transfer    the anchor's SrV value moved by the MiD 2023 regional ratio Kreis k / anchor
  mid_direct  the MiD 2023 regional value of Kreis k itself (has_ebike only: for the other
              attributes the two surveys differ in level by construction)
Anchors: Braunschweig (03101), and the region total without k (leave-one-out in both surveys,
each with its own weights).

Attributes (MiD tables committed under eqasim-data/data/braunschweig/mid/, regenerated by
scripts/extract_mid_tables.py):
  has_ebike             households with >= 1 e-bike/pedelec; MiD H12.1; odds-ratio transfer.
  leisure, escort       persons with >= 1 trip of the purpose on an average weekday (SrV
                        E_ZWECK_9 7 / 6, the committed participation targets). Transfer scales
                        the anchor share by the purpose trip rate per person. "MiD rate" = W1
                        purpose share x P39.1 mean trips (the chain usable for Wolfsburg);
                        "SrV rate" = SrV's own rate of k, which isolates the assumption
                        "participation is proportional to the purpose trip rate".
  trip_class            trip classes 0 / 1-2 / 3-4 / 5+. "P39.1": class-wise transfer with the
                        MiD trip-count classes. "P36.1": trips_0 scaled by the MiD immobile
                        ratio, the mobile classes keep the anchor's pattern (the Wolfsburg rule
                        of scripts/build_trip_class_target.py).

Outputs (--out-dir): backtest_errors.csv (one row per attribute x quantity x anchor x Kreis),
backtest_summary.csv (mean absolute errors, all Kreise and the two kreisfreie Staedte) and
trips_per_participant.csv (SrV, by Kreis). Needs the local-only SrV microdata (--srv-raw-dir,
file names as in scripts/build_srv_participation_aggregate.py); every other input is committed.

Usage:
    python scripts/backtest_wolfsburg_kreis_transfer.py --srv-raw-dir <dir> [--data <dir>] [--out-dir <dir>]
"""
from __future__ import annotations

import argparse
import logging
import sys
from pathlib import Path

import pandas as pd

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))
from scripts.build_blended_kreis_targets import mid_h12_1_ebike_share  # noqa: E402
from scripts.build_srv_participation_aggregate import (  # noqa: E402
    CSV_READ_KWARGS, PURPOSE, compute_participation, load_kreis_by_hhnr)

logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
log = logging.getLogger("backtest_wolfsburg_kreis_transfer")

DATA_DEFAULT = REPO / "eqasim-data" / "data" / "braunschweig"
OUT_DEFAULT = DATA_DEFAULT / "calibration" / "wolfsburg_transfer_backtest_2026-11-20"
BRAUNSCHWEIG = "03101"
SALZGITTER = "03102"
WOLFSBURG = "03103"
REGION = "region_without_k"
# The seven Kreise SrV 2023 surveys (Wolfsburg 03103 is the one it does not).
SRV_KREISE = ["03101", "03102", "03151", "03153", "03154", "03157", "03158"]
TRIP_CLASSES = ["trips_0", "trips_1_2", "trips_3_4", "trips_5plus"]
P39_1_COLUMNS = ["wege_0", "wege_1", "wege_2", "wege_3", "wege_4", "wege_5plus"]
# Max deviation tolerated between the participation recomputed here and the committed table.
PARTICIPATION_REPRODUCTION_TOLERANCE = 1e-5


# ---------------------------------------------------------------------------- formulas

def leave_one_out(total: float, total_weight: float, value_k: float, weight_k: float) -> float:
    """Region value without Kreis k, from the region total and k's own value and weight."""
    if total_weight - weight_k <= 0:
        raise ValueError(f"leave_one_out: no weight left without k ({total_weight} - {weight_k})")
    return (total * total_weight - value_k * weight_k) / (total_weight - weight_k)


def odds_transfer(anchor_share: float, mid_k: float, mid_anchor: float) -> float:
    """Anchor share moved by the MiD odds ratio of Kreis k to the anchor."""
    odds = (anchor_share / (1 - anchor_share)) * (mid_k / (1 - mid_k)) / (mid_anchor / (1 - mid_anchor))
    return odds / (1 + odds)


def class_transfer(anchor_shares: list[float], mid_k: list[float], mid_anchor: list[float]) -> list[float]:
    """Class shares of the anchor, each moved by the MiD ratio k / anchor, renormalised."""
    raw = [a * k / m for a, k, m in zip(anchor_shares, mid_k, mid_anchor)]
    return [r / sum(raw) for r in raw]


def immobile_transfer(anchor_shares: list[float], mid_immobile_k: float,
                      mid_immobile_anchor: float) -> list[float]:
    """trips_0 scaled by the MiD immobile ratio; the mobile classes keep the anchor's pattern."""
    trips_0 = anchor_shares[0] * mid_immobile_k / mid_immobile_anchor
    mobile = sum(anchor_shares[1:])
    return [trips_0] + [s / mobile * (1 - trips_0) for s in anchor_shares[1:]]


# ---------------------------------------------------------------------------- inputs

def read_table(path: Path, key: str) -> pd.DataFrame:
    if not path.exists():
        raise FileNotFoundError(f"required input missing: {path}")
    df = pd.read_csv(path, comment="#", dtype={key: str})
    return df


def mid_table(data: Path, name: str) -> pd.DataFrame:
    """A committed MiD regional table indexed by ars5, the Gesamt row keyed 'TOT'."""
    df = read_table(data / "mid" / name, "ars5")
    df["ars5"] = df["ars5"].replace({"03ZGB": "TOT"})
    return df.set_index("ars5")


def srv_table(data: Path, name: str) -> pd.DataFrame:
    """A committed SrV aggregate table indexed by code, the total row keyed 'TOT'."""
    df = read_table(data / "srv" / name, "code")
    df.loc[df["level"] == "total", "code"] = "TOT"
    return df[df["level"].isin(["kreis", "total"])].set_index("code")


def load_srv_persons(data: Path, raw_dir: Path) -> pd.DataFrame:
    """SrV persons of the average weekday with their leisure / escort trip counts.

    Reproduces the committed participation table first (same code path, same universe) and
    raises when it does not: the backtest must score against exactly the committed targets.
    """
    households = raw_dir / "SrV2023_Haushalte.csv"
    persons_path = raw_dir / "SrV2023_Personen.csv"
    trips_path = raw_dir / "SrV2023_Wege.csv"
    for path in (households, persons_path, trips_path):
        if not path.exists():
            raise FileNotFoundError(f"SrV microdata missing: {path}")
    persons = pd.read_csv(persons_path, **CSV_READ_KWARGS)
    persons["kreis"] = persons["HHNR"].map(load_kreis_by_hhnr(households))
    persons = persons[persons["MITTL_WERKTAG"] == 1].copy()
    trips = pd.read_csv(trips_path, usecols=["HHNR", "PNR", "E_ZWECK_9"], **CSV_READ_KWARGS)

    recomputed = compute_participation(persons, trips).set_index("code")
    committed = srv_table(data, "srv2023_participation_by_kreis.csv")
    deviation = (recomputed.loc[SRV_KREISE, list(PURPOSE)]
                 - committed.loc[SRV_KREISE, list(PURPOSE)]).abs().max().max()
    if deviation > PARTICIPATION_REPRODUCTION_TOLERANCE:
        raise RuntimeError(f"participation recomputed from {raw_dir} deviates from the committed "
                           f"table by {deviation:.2e}; the backtest would score a different target.")
    log.info("participation reproduced from the microdata (max deviation %.1e)", deviation)

    persons["pid"] = persons["HHNR"].astype(str) + "_" + persons["PNR"].astype(str)
    persons["w"] = pd.to_numeric(persons["GEWICHT_P_ZENSUS"], errors="coerce").fillna(0.0)
    trips["pid"] = trips["HHNR"].astype(str) + "_" + trips["PNR"].astype(str)
    for purpose in ("leisure", "escort"):
        counts = trips[trips["E_ZWECK_9"].isin(PURPOSE[purpose])].groupby("pid").size()
        persons[f"n_{purpose}"] = persons["pid"].map(counts).fillna(0)
    return persons


def participation_and_rate(persons: pd.DataFrame, purpose: str) -> tuple[float, float]:
    """(weighted share with >= 1 trip of the purpose, weighted purpose trips per person)."""
    weight = persons["w"].sum()
    share = persons.loc[persons[f"n_{purpose}"] > 0, "w"].sum() / weight
    rate = (persons[f"n_{purpose}"] * persons["w"]).sum() / weight
    return share, rate


# ---------------------------------------------------------------------------- backtest

def mid_anchor_value(values: dict, weights: dict, anchor: str, k: str):
    """MiD value of the anchor: Braunschweig, or the Gesamt row without Kreis k AND Wolfsburg.

    The MiD Gesamt row covers all eight Kreise; the SrV region it is paired with never holds
    Wolfsburg, so both Wolfsburg and k leave the MiD side (the anchor is built the same way in
    both surveys).
    """
    if anchor == BRAUNSCHWEIG:
        return values[BRAUNSCHWEIG]

    def without(total, weight, value_of):
        for code in (WOLFSBURG, k):
            total = leave_one_out(total, weight, value_of(code), weights[code])
            weight -= weights[code]
        return total

    if isinstance(values["TOT"], list):
        return [without(t, weights["TOT"], lambda code, i=i: values[code][i])
                for i, t in enumerate(values["TOT"])]
    return without(values["TOT"], weights["TOT"], lambda code: values[code])


def run_backtest(data: Path, persons: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame]:
    rows = []

    def record(attribute, quantity, anchor, k, actual, copy_pred, transfer_pred, mid_direct=None):
        rows.append({"attribute": attribute, "quantity": quantity, "anchor": anchor, "ars5": k,
                     "actual": actual, "copy_pred": copy_pred, "transfer_pred": transfer_pred,
                     "mid_direct_pred": mid_direct})

    def pairs():
        for anchor in (BRAUNSCHWEIG, REGION):
            for k in SRV_KREISE:
                if not (anchor == BRAUNSCHWEIG and k == BRAUNSCHWEIG):
                    yield anchor, k

    def persons_of(anchor, k):
        if anchor == BRAUNSCHWEIG:
            return persons[persons["kreis"] == BRAUNSCHWEIG]
        return persons[persons["kreis"].isin([c for c in SRV_KREISE if c != k])]

    # leisure / escort participation
    p391 = mid_table(data, "mid2023_P39_1.csv")
    w1 = mid_table(data, "mid2023_W1.csv")
    person_weights = p391["n_weighted"].to_dict()
    trip_stats = []
    for purpose, w1_column in (("leisure", "freizeit"), ("escort", "begleitung")):
        mid_rate = {c: w1.loc[c, w1_column] / 100 * p391.loc[c, "mittel"] for c in p391.index}
        for anchor, k in pairs():
            actual, own_rate = participation_and_rate(persons[persons["kreis"] == k], purpose)
            anchor_share, anchor_rate = participation_and_rate(persons_of(anchor, k), purpose)
            record(f"{purpose}_srv_rate", "share", anchor, k, actual, anchor_share,
                   anchor_share * own_rate / anchor_rate)
            mid_anchor = mid_anchor_value(mid_rate, person_weights, anchor, k)
            record(f"{purpose}_mid_rate", "share", anchor, k, actual, anchor_share,
                   anchor_share * mid_rate[k] / mid_anchor)
    for k in SRV_KREISE + ["TOT"]:
        group = persons if k == "TOT" else persons[persons["kreis"] == k]
        stats = {"ars5": "03ZGB_srv7" if k == "TOT" else k}
        for purpose in ("leisure", "escort"):
            share, rate = participation_and_rate(group, purpose)
            stats[f"{purpose}_participation"] = share
            stats[f"{purpose}_trips_per_participant"] = rate / share
        trip_stats.append(stats)

    # has_ebike
    h121 = mid_table(data, "mid2023_H12_1.csv")
    # The same share the target builder uses for Wolfsburg (one definition, one place).
    mid_ebike = {c: mid_h12_1_ebike_share(data, "03ZGB" if c == "TOT" else c)[0]
                 for c in h121.index}
    household_weights = h121["n_weighted"].to_dict()
    ebike = srv_table(data, "srv2023_ebike_household_by_kreis.csv")
    for anchor, k in pairs():
        actual = ebike.loc[k, "share_hh_with_ebike"]
        if anchor == BRAUNSCHWEIG:
            anchor_share = ebike.loc[BRAUNSCHWEIG, "share_hh_with_ebike"]
        else:
            anchor_share = leave_one_out(ebike.loc["TOT", "share_hh_with_ebike"],
                                         ebike.loc["TOT", "n_weighted"], actual,
                                         ebike.loc[k, "n_weighted"])
        mid_anchor = mid_anchor_value(mid_ebike, household_weights, anchor, k)
        record("has_ebike", "share", anchor, k, actual, anchor_share,
               odds_transfer(anchor_share, mid_ebike[k], mid_anchor), mid_ebike[k])

    # trip_class
    classes = srv_table(data, "srv2023_trip_classes_by_kreis.csv")
    mid_classes = {}
    for c in p391.index:
        v = [p391.loc[c, col] for col in P39_1_COLUMNS]
        counts = [v[0], v[1] + v[2], v[3] + v[4], v[5]]
        mid_classes[c] = [x / sum(counts) for x in counts]
    p361 = mid_table(data, "mid2023_P36_1.csv")
    mid_immobile = p361["nicht_mobil"].to_dict()
    p361_weights = p361["n_weighted"].to_dict()
    for anchor, k in pairs():
        actual = [classes.loc[k, c] for c in TRIP_CLASSES]
        if anchor == BRAUNSCHWEIG:
            anchor_shares = [classes.loc[BRAUNSCHWEIG, c] for c in TRIP_CLASSES]
        else:
            anchor_shares = [leave_one_out(classes.loc["TOT", c], classes.loc["TOT", "n_weighted"],
                                           classes.loc[k, c], classes.loc[k, "n_weighted"])
                             for c in TRIP_CLASSES]
        by_classes = class_transfer(anchor_shares, mid_classes[k],
                                    mid_anchor_value(mid_classes, person_weights, anchor, k))
        by_immobile = immobile_transfer(anchor_shares, mid_immobile[k],
                                        mid_anchor_value(mid_immobile, p361_weights, anchor, k))
        for i, c in enumerate(TRIP_CLASSES):
            record("trip_class_p39_1", c, anchor, k, actual[i], anchor_shares[i], by_classes[i])
            record("trip_class_p36_1", c, anchor, k, actual[i], anchor_shares[i], by_immobile[i])

    return pd.DataFrame(rows), pd.DataFrame(trip_stats)


def summarise(errors: pd.DataFrame) -> pd.DataFrame:
    """Mean absolute errors (pp) per attribute x anchor, over all Kreise and for the two cities."""
    df = errors.copy()
    for col in ("copy", "transfer", "mid_direct"):
        df[f"{col}_abs_err_pp"] = (df[f"{col}_pred"].astype(float) - df["actual"]).abs() * 100
    trips_0 = df[df["quantity"] == "trips_0"].assign(quantity_set="trips_0")
    df = pd.concat([df.assign(quantity_set="all"), trips_0])
    out = []
    for (attribute, quantity_set, anchor), g in df.groupby(["attribute", "quantity_set", "anchor"],
                                                          sort=False):
        rec = {"attribute": attribute, "quantity_set": quantity_set, "anchor": anchor,
               "n_kreise": g["ars5"].nunique()}
        for col in ("copy", "transfer", "mid_direct"):
            rec[f"mae_{col}_pp"] = g[f"{col}_abs_err_pp"].mean()
        for city, name in ((BRAUNSCHWEIG, "bs"), (SALZGITTER, "sz")):
            c = g[g["ars5"] == city]
            for col in ("copy", "transfer", "mid_direct"):
                rec[f"{name}_{col}_abs_err_pp"] = c[f"{col}_abs_err_pp"].mean() if len(c) else None
        out.append(rec)
    return pd.DataFrame(out)


HEADER = """\
# Backtest of the Wolfsburg rules for the per-Kreis control targets (ADR-0205), written by
# scripts/backtest_wolfsburg_kreis_transfer.py from the committed MiD 2023 regional tables
# (H12.1, P36.1, P39.1, W1), the committed SrV 2023 aggregates and the local-only SrV 2023
# microdata (average weekday, GEWICHT_P_ZENSUS). Each SrV Kreis is predicted as if SrV had not
# surveyed it; anchors: Braunschweig, or the region without the Kreis (leave-one-out).
"""


def write_csv(df: pd.DataFrame, path: Path, note: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.write(HEADER + f"# {note}\n")
        df.round(6).to_csv(f, index=False)
    log.info("wrote %s (%d rows)", path, len(df))


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--data", type=Path, default=DATA_DEFAULT)
    parser.add_argument("--srv-raw-dir", type=Path, required=True)
    parser.add_argument("--out-dir", type=Path, default=OUT_DEFAULT)
    args = parser.parse_args(argv)

    persons = load_srv_persons(args.data, args.srv_raw_dir)
    errors, trip_stats = run_backtest(args.data, persons)
    summary = summarise(errors)
    write_csv(errors, args.out_dir / "backtest_errors.csv",
              "One row per attribute x quantity x anchor x Kreis; shares as fractions.")
    write_csv(summary, args.out_dir / "backtest_summary.csv",
              "Mean absolute errors in percentage points; bs_/sz_ = the two kreisfreie Staedte.")
    write_csv(trip_stats, args.out_dir / "trips_per_participant.csv",
              "SrV purpose trips per participant and participation share, by Kreis "
              "(03ZGB_srv7 = the seven SrV Kreise together).")
    for _, r in summary[summary["quantity_set"] == "all"].iterrows():
        log.info("%-18s %-16s MAE copy %.2f  transfer %.2f  mid_direct %s",
                 r["attribute"], r["anchor"], r["mae_copy_pp"], r["mae_transfer_pp"],
                 "n/a" if pd.isna(r["mae_mid_direct_pp"]) else f"{r['mae_mid_direct_pp']:.2f}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
