"""Pins for the committed srv2023_mode_by_distance_band.csv (eqasim-bs#453).

Values are read from the committed CSV generated by scripts/extract_srv_mode_by_distance_band.py on
2026-10-15 against the local-only SrV 2023 raw trips (n_selected = 45942 trips). They are pins, not
re-derivations: a change here signals that the committed table changed.
"""
from pathlib import Path

import numpy as np
import pytest

from braunschweig.calibration import srv_mode_by_distance_band as M

SRV_DIR = Path(__file__).resolve().parents[1] / "eqasim-data" / "data" / "braunschweig" / "srv"


@pytest.fixture(scope="module")
def table():
    return M.load_table(SRV_DIR)


def test_every_group_band_cell_has_all_five_modes_summing_to_one(table):
    sizes = table.groupby(["purpose_group", "band"]).size()
    assert (sizes == len(M.MODES)).all()
    sums = table.groupby(["purpose_group", "band"])["share"].sum()
    assert np.allclose(sums.to_numpy(), 1.0, atol=1e-5)
    assert set(table["purpose_group"]) == set(M.PURPOSE_GROUPS) | {M.ALL_GROUP}


def test_walk_share_is_below_one_percent_from_five_kilometres_for_work_and_education(table):
    # Walk must be IMPLAUSIBLE (share below the stage's 1 % min_share default) from 5 km for work and education,
    # not exactly zero: an earlier probe claimed zero because it counted only trips TO work/education, while the
    # table also counts home returns and business / other-education trips. Measured maximum is 0.0016 (5 unweighted
    # walk trips in total beyond 5 km); the three non-zero cells are pinned exactly. The other and all groups
    # (leisure walks, hikes) are pinned by value below.
    far = table[(table["mode"] == "walk") & (table["band_lower_km"] >= 5.0)
                & table["purpose_group"].isin(["work", "education"])]
    assert len(far) > 0 and (far["share"] < 0.01).all()
    nonzero = far[far["share"] > 0].set_index(["purpose_group", "band"])["share"]
    assert nonzero.round(6).to_dict() == {("work", "5_10"): 0.001604, ("work", "45_plus"): 0.001412,
                                          ("education", "5_10"): 0.000792}


def test_walk_shares_beyond_five_kilometres_for_other_and_all_pin(table):
    far = table[(table["mode"] == "walk") & (table["band_lower_km"] >= 5.0)
                & table["purpose_group"].isin(["other", "all"])].set_index(["purpose_group", "band"])["share"]
    assert far.round(6).to_dict() == {
        ("other", "5_10"): 0.010481, ("other", "10_15"): 0.001027, ("other", "15_20"): 0.007572,
        ("other", "20_30"): 0.009808, ("other", "30_45"): 0.006431, ("other", "45_plus"): 0.0,
        ("all", "5_10"): 0.006809, ("all", "10_15"): 0.000512, ("all", "15_20"): 0.003222,
        ("all", "20_30"): 0.003118, ("all", "30_45"): 0.001748, ("all", "45_plus"): 0.000807}


def test_an_always_available_mode_is_plausible_in_every_cell_at_one_percent(table):
    # The stage's load-time assertion (Task 3): pt or walk must reach 1 % in every cell, else a person without a
    # car, a licence or a bicycle could have no substitute.
    best = table[table["mode"].isin(["pt", "walk"])].groupby(["purpose_group", "band"])["share"].max()
    assert (best >= 0.01).all(), best[best < 0.01].to_dict()


def test_row_count_and_selected_trips_pin(table):
    assert len(table) == 135                                      # printed by the extractor ("wrote ... rows")
    work_n_band = table[(table["purpose_group"] == "work") & (table["mode"] == "car")].set_index("band")["n_band"]
    assert work_n_band["0_5"] == 3583                              # n_band of the work 0_5 band in the CSV
    assert table.loc[(table["purpose_group"] == "education"), "band"].str.endswith("plus").sum() == len(M.MODES)


def test_open_top_band_reads_back_as_infinity(table):
    top = table[table["band"].str.endswith("plus")]
    assert np.isinf(top["band_upper_km"]).all()
