# Pin tests: real values from the committed CSV (generated by
# scripts/extract_srv_plan_structure.py against the local-only SrV 2023 raw microdata).
# Values are pins, not re-derivations: a change here signals that the committed table changed,
# not that the extraction logic is wrong.
