# --------------------------------------------------------------------------- reference table
def test_build_reference_universes_differ_in_the_away_person():
    persons, trips = _harmonised()
    zero = T.build_reference(persons, trips, universe=T.UNIVERSE_AT_HOME_ZERO)
    only = T.build_reference(persons, trips, universe=T.UNIVERSE_AT_HOME_ONLY)

    def value(df, metric, segment="all"):
        row = df[(df["segment"] == segment) & (df["metric"] == metric)]
        assert len(row) == 1, "%s not unique in segment %s" % (metric, segment)
        return float(row["value"].iloc[0])

    assert set(zero["universe"]) == {T.UNIVERSE_AT_HOME_ZERO}
    assert value(zero, "n_persons_unweighted") == 6
    assert value(only, "n_persons_unweighted") == 5
    assert int(zero[zero["segment"] == "all"]["n_unweighted"].iloc[0]) == 6
    assert int(only[only["segment"] == "all"]["n_unweighted"].iloc[0]) == 5
    assert value(zero, "mobility_rate") == pytest.approx(5.0 / 7.0)
    assert value(only, "mobility_rate") == pytest.approx(5.0 / 6.0)


def test_build_reference_contains_every_expected_segment():
    persons, trips = _harmonised()
    table = T.build_reference(persons, trips, universe=T.UNIVERSE_AT_HOME_ZERO)
    segments = set(table["segment"])
    assert "all" in segments
    assert {"age_%s" % b for b in T.AGE_LABELS} <= segments
    assert {"group_%s" % g for g in T.GROUPS} <= segments
    assert {"sex_male", "sex_female"} <= segments
    assert {"kreis_%s" % BRAUNSCHWEIG_KREIS, "kreis_%s" % SALZGITTER_KREIS} <= segments
    assert list(table.columns) == ["universe", "segment", "metric", "value", "n_unweighted"]
    # every segment carries the same metric set (a long table with holes would break Task 10)
    per_segment = table.groupby("segment")["metric"].apply(set)
    assert all(s == per_segment.iloc[0] for s in per_segment)


def test_build_reference_rejects_an_unknown_universe():
    persons, trips = _harmonised()
    with pytest.raises(ValueError, match="universe"):
        T.build_reference(persons, trips, universe="everybody")


