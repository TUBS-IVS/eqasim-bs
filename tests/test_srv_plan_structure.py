SRV_DIR = Path(__file__).resolve().parents[1] / "eqasim-data" / "data" / "braunschweig" / "srv"


@pytest.fixture(scope="module")
def committed_table():
    """The committed reference table, or a SKIP naming the file.

    The path is gitignored-with-an-allowlist, so a checkout without it must skip loudly rather
    than let the pins below pass vacuously on an empty frame.
    """
    path = SRV_DIR / T.PLAN_STRUCTURE_TABLE
    if not path.exists():
        pytest.skip("committed plan-structure reference missing: %s (regenerate with "
                    "scripts/extract_srv_plan_structure.py against the local-only SrV raw)"
                    % path)
    table = T.load_plan_structure_reference(SRV_DIR)
    assert len(table) > 0, "committed plan-structure reference is empty: %s" % path
    return table


def _committed_value(table, universe, metric, segment="all"):
    row = table[(table["universe"] == universe) & (table["segment"] == segment)
                & (table["metric"] == metric)]
    assert len(row) == 1, "%s/%s/%s is not a single row" % (universe, segment, metric)
    return float(row["value"].iloc[0])


def test_committed_table_shape_and_columns(committed_table):
    assert list(committed_table.columns) == T.REFERENCE_COLUMNS
    assert set(committed_table["universe"]) == set(T.UNIVERSES)
    assert committed_table["segment"].nunique() == 23      # all + 8 age + 5 group + 2 sex + 7 kreis
    assert len(committed_table) == 9476


def test_committed_at_home_zero_pinned_values(committed_table):
    assert _committed_value(committed_table, T.UNIVERSE_AT_HOME_ZERO,
                            "n_persons_unweighted") == 18223
    assert _committed_value(committed_table, T.UNIVERSE_AT_HOME_ZERO,
                            "mobility_rate") == pytest.approx(0.8437, abs=0.001)
    assert _committed_value(committed_table, T.UNIVERSE_AT_HOME_ZERO,
                            "trips_per_person") == pytest.approx(3.1865, abs=0.001)
    assert _committed_value(committed_table, T.UNIVERSE_AT_HOME_ZERO,
                            "participation_work") == pytest.approx(0.3316, abs=0.001)
    assert _committed_value(committed_table, T.UNIVERSE_AT_HOME_ZERO,
                            "participation_shop") == pytest.approx(0.2794, abs=0.001)
    assert _committed_value(committed_table, T.UNIVERSE_AT_HOME_ZERO,
                            "participation_leisure") == pytest.approx(0.3832, abs=0.001)


def test_committed_at_home_only_pinned_values(committed_table):
    assert _committed_value(committed_table, T.UNIVERSE_AT_HOME_ONLY,
                            "n_persons_unweighted") == 17269
    assert _committed_value(committed_table, T.UNIVERSE_AT_HOME_ONLY,
                            "mobility_rate") == pytest.approx(0.8879, abs=0.001)


def test_committed_purpose_shares_sum_to_one(committed_table):
    shares = committed_table[committed_table["metric"].isin(
        ["purpose_share_%s" % purpose for purpose in T.PURPOSES])]
    totals = shares.groupby(["universe", "segment"])["value"].sum()
    populated = totals[totals.notna() & (totals != 0.0)]
    assert len(populated) > 0
    assert np.allclose(populated.values, 1.0, atol=1e-6)
