def test_departure_time_table_raises_on_a_trip_with_an_unknown_person():
    persons, trips = _fixture()
    trips = pd.concat([trips, pd.DataFrame({
        "pid": ["ghost"], "seq": [1], "weight": [1.0], "purpose": ["work"],
        "prev_purpose": ["home"], "dep_min": [400.0], "arr_min": [420.0],
    })], ignore_index=True)
    with pytest.raises(ValueError, match="not in the person frame"):
        T.departure_time_table(persons, trips, np.random.RandomState(0))


# --------------------------------------------------------------------------- activity_duration_table
def test_activity_duration_excludes_a_25_hour_gap_and_counts_it():
    persons, trips = _fixture()
    table = T.activity_duration_table(persons, trips)
    # p3's shop activity (25 h) must not appear anywhere in the output.
    subset = table[(table["segment"] == "employed") & (table["purpose"] == "shop")]
    assert len(subset) == 0
    assert table.attrs["n_legs_total"] == 7
    assert table.attrs["n_legs_excluded_out_of_range"] == 1
    assert table.attrs["n_legs_excluded_no_next_or_missing_time"] == 4
    assert table.attrs["n_legs_included"] == 2


def test_activity_duration_bands_are_complete_and_sum_to_one():
    persons, trips = _fixture()
    table = T.activity_duration_table(persons, trips)
    subset = table[(table["segment"] == "employed") & (table["purpose"] == "work")]
    assert sorted(subset["band"]) == sorted(T.DURATION_BAND_LABELS)
    assert subset["share"].sum() == pytest.approx(1.0)
    by_band = subset.set_index("band")["share"]
    # p2 trip 1 (weight 1.0, 8.667 h) -> "8h+"; p3 trip 1 (weight 2.0, 0.5 h) -> "0-0.5h".
    assert by_band["8h+"] == pytest.approx(1.0 / 3.0)
    assert by_band["0-0.5h"] == pytest.approx(2.0 / 3.0)
    assert by_band["1-2h"] == pytest.approx(0.0)
    assert int(subset["n_unweighted"].iloc[0]) == 2


def test_activity_duration_table_columns_and_universe():
    persons, trips = _fixture()
