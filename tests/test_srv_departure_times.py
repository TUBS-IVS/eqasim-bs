def test_committed_departure_time_reference_is_internally_consistent():
    path = SRV_DIR / T.DEPARTURE_TIME_TABLE
    if not path.exists():
        pytest.skip("committed SrV departure-time reference not present in this checkout")
    table = pd.read_csv(path, comment="#")
    assert list(table.columns) == T.DEPARTURE_TIME_COLUMNS
    assert set(table["universe"]) == {"at_home_zero"}
    assert set(table["position"]) <= set(T.POSITIONS)
    assert table["bin_15min"].between(0, T.N_BINS - 1).all()
    grouped = table.groupby(["segment", "purpose", "position"])
    assert np.allclose(grouped["share_derounded"].sum().values, 1.0, atol=1e-6)
    assert np.allclose(grouped["share_as_reported"].sum().values, 1.0, atol=1e-6)


