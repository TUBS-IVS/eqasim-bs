def test_departure_time_table_is_dense_over_all_bins_and_purposes():
    persons, trips = _fixture()
    table = T.departure_time_table(persons, trips, np.random.RandomState(6))
    assert len(table) == len(T.SEGMENTS) * len(T.PURPOSES_WITH_ALL) * len(T.POSITIONS) * T.N_BINS
    counts = table.groupby(["segment", "purpose", "position"]).size()
    assert (counts == T.N_BINS).all()
    assert set(table["purpose"]) == set(T.PURPOSES_WITH_ALL)


def test_departure_time_table_empty_cell_is_emitted_with_nan_shares_never_dropped():
    persons, trips = _fixture()
    table = T.departure_time_table(persons, trips, np.random.RandomState(7))
    # p1 (segment "school_age_6_17_not_employed") has a single trip, purpose "education" -- the
    # "work" purpose cell for this segment has zero contributing legs.
    empty = table[(table["segment"] == "school_age_6_17_not_employed")
                  & (table["purpose"] == "work") & (table["position"] == "first")]
    assert len(empty) == T.N_BINS
    assert (empty["n_unweighted"] == 0).all()
    assert empty["share_derounded"].isna().all()
    assert empty["share_as_reported"].isna().all()


def test_first_trip_derounded_bin_stays_within_the_reporting_cell():
    # A 7:00 (420 min) quarter-hour report de-rounds to [412.5, 427.5), which can only ever land
    # in 15-minute bin 27 or 28 -- never 26 (< 412.5) or 29 (>= 427.5), for ANY offset drawn.
    persons, trips = _fixture()
    table = T.departure_time_table(persons, trips, np.random.RandomState(0))
    subset = table[(table["segment"] == "school_age_6_17_not_employed")
                   & (table["purpose"] == "education") & (table["position"] == "first")]
    assert len(subset) == T.N_BINS
    nonzero_derounded = subset[subset["share_derounded"] > 0]
    assert set(nonzero_derounded["bin_15min"]) <= {27, 28}
    assert subset.loc[subset["bin_15min"].isin([26, 29]), "share_derounded"].sum() == 0.0
    assert subset["share_derounded"].sum() == pytest.approx(1.0)
    assert subset["share_as_reported"].sum() == pytest.approx(1.0)
    # The as-reported time is exact (420 / 15 = 28.0), so its bin is always 28.
    assert subset.loc[subset["bin_15min"] == 28, "share_as_reported"].iloc[0] == pytest.approx(1.0)


def test_shares_sum_to_one_per_segment_purpose_position():
    persons, trips = _fixture()
    table = T.departure_time_table(persons, trips, np.random.RandomState(1))
    subset = table[(table["segment"] == "employed") & (table["purpose"] == "work")
                   & (table["position"] == "first")]
    assert len(subset) == T.N_BINS
    nonzero = subset[subset["share_as_reported"] > 0]
    assert len(nonzero) == 2   # p2 trip 1 (bin 32) and p3 trip 1 (bin 34)
    assert subset["share_derounded"].sum() == pytest.approx(1.0)
    assert subset["share_as_reported"].sum() == pytest.approx(1.0)
    assert int(subset["n_unweighted"].iloc[0]) == 2

    # Invariant must hold for every NON-EMPTY (segment, purpose, position) triple in the table
    # (an empty cell's shares are NaN by design and must not be forced into this check).
    non_empty = table[table["n_unweighted"] > 0]
    grouped = non_empty.groupby(["segment", "purpose", "position"])
    assert np.allclose(grouped["share_derounded"].sum().values, 1.0)
    assert np.allclose(grouped["share_as_reported"].sum().values, 1.0)


def test_pooled_purpose_all_exists_and_sums_to_one():
    persons, trips = _fixture()
