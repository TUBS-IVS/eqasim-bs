"""Tests for the SrV 2023 departure-time and activity-duration reference builder (issue #123,
Phase 0 Task 2; fix round 1, review ruling A-R9/A-R10).

The logic tests run on tiny, hand-built HARMONISED fixtures (the schema produced by
``srv_plan_structure.harmonise_srv``, not the raw SrV column names) -- the real SrV 2023
scientific-use microdata is local-only and must never be a test dependency. Every expected value
below is derivable by hand from the docstrings of :func:`_fixture` and :func:`_unknown_purpose_fixture`.

Pin test at the bottom reads the COMMITTED CSVs generated by
``scripts/extract_srv_departure_times.py`` against the local-only raw microdata and only checks
structural invariants (never numeric pins from a run) -- it skips (never silently passes) when the
committed files are absent.
"""
from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd
import pytest

from braunschweig.calibration import srv_departure_times as T
from braunschweig.calibration import srv_plan_structure as SRV

REPO = Path(__file__).resolve().parents[1]
SRV_DIR = REPO / "eqasim-data" / "data" / "braunschweig" / "srv"


def _fixture():
    """3 persons, 7 trips (6 with a valid ``dep_min``), in the HARMONISED schema.

    ==== ============================== ====== ============================================
    pid  group                          weight reporting day
    ==== ============================== ====== ============================================
    p1   school_age_6_17_not_employed   3.0    one trip, 7:00 (420 min) to education
    p2   employed                       1.0    work@8:00 (480), home@17:00 (1020), then a
                                                trip with an unrecorded ("keine Angabe")
                                                departure time (dep_min/arr_min NaN)
    p3   employed                       2.0    work@8:30 (510), shop@9:20 (560), then a trip
                                                at 2080 min (34:40 -- past the 28 h window)
    ==== ============================== ====== ============================================

    Derivable expectations:

    * ``p2``'s third trip has ``dep_min`` NaN and is the ONLY invalid leg -> 6/7 legs valid,
      1 excluded (NaN).
    * ``p1``'s single trip is a quarter-hour report (420 % 15 == 0, half-width 7.5 min), so its
      de-rounded value lies in [412.5, 427.5) and its 15-minute bin is 27 (412.5/15 = 27.5) or 28
      (420/15 = 28.0 exactly), never 26 or 29.
    * segment "employed", purpose "work", position "first": ``p2`` trip 1 (weight 1.0, bin 32)
      and ``p3`` trip 1 (weight 2.0, bin 34) -> two bins, shares summing to 1.0 over weight 3.0.
    * segment "employed", purpose "home", position "later": only ``p2`` trip 2 (weight 1.0,
      1020 min, bin 68, no clipping) -> "home" never appears under position "first" (no one's
      first trip is a return home) and "work" never appears under "later" (neither ``p2`` nor
      ``p3`` has a later trip to work) -- this is the "later excludes seq-min legs" check.
    * ``p3``'s third trip departs at 2080 min (138.7 quarter-hours), whose raw AND de-rounded bin
      (138, clipped to 111) both exceed ``N_BINS - 1`` -> exactly 1 of the 6 valid legs is
      clipped in each of ``share_as_reported`` / ``share_derounded``.
    * Activity durations (next ``dep_min`` minus ``arr_min`` within the pid): ``p1`` trip 1 and
      ``p2`` trip 3 and ``p3`` trip 3 have no following trip (excluded, "no next"); ``p2`` trip 2
      has no next EITHER (its only following trip has a NaN ``dep_min``, also "no next"); ``p2``
      trip 1 -> (1020 - 500) / 60 = 8.667 h ("8h+"); ``p3`` trip 1 -> (560 - 530) / 60 = 0.5 h
      ("0-0.5h"); ``p3`` trip 2 -> (2080 - 580) / 60 = 25.0 h, OUTSIDE [0, 20] h -> EXCLUDED and
      counted. So of 7 trips: 4 have no measurable next activity, 1 is measured but out of range,
      2 are included (segment "employed", purpose "work": bands "0-0.5h" share 2/3, "8h+" 1/3).
    * No person in this fixture has an unknown-purpose leg -- see :func:`_unknown_purpose_fixture`
      for that case.
    """
    persons = pd.DataFrame({
        "pid": ["p1", "p2", "p3"],
        "weight": [3.0, 1.0, 2.0],
        "group": ["school_age_6_17_not_employed", "employed", "employed"],
    })
    trips = pd.DataFrame({
        "pid":          ["p1", "p2", "p2", "p2", "p3", "p3", "p3"],
        "seq":          [1, 1, 2, 3, 1, 2, 3],
        "weight":       [3.0, 1.0, 1.0, 1.0, 2.0, 2.0, 2.0],
        "purpose":      ["education", "work", "home", "leisure", "work", "shop", "other"],
        "prev_purpose": ["home", "home", "work", "home", "home", "work", "shop"],
        "dep_min":      [420.0, 480.0, 1020.0, np.nan, 510.0, 560.0, 2080.0],
        "arr_min":      [450.0, 500.0, 1040.0, np.nan, 530.0, 580.0, 2100.0],
    })
    return persons, trips


def _unknown_purpose_fixture():
    """2 persons, 4 trips, one of them an UNKNOWN-purpose destination (ruling A-R10).

    ==== ============================== ====== ================================================
    pid  group                          weight reporting day
    ==== ============================== ====== ================================================
    u1   employed                       1.0    work@8:00 (480, arr 500, first), UNKNOWN@10:00
                                                (600, arr 620, later), home@10:50 (650, later)
    u2   employed                       1.0    shop@8:20 (500, arr 520, first, no next trip)
    ==== ============================== ====== ================================================

    Derivable expectations:

    * ``u1``'s second trip (unknown destination purpose, valid dep_min=600) must NEVER appear
      under a NAMED purpose (segment "employed" position "later" purpose "home" has exactly 1
      leg -- ``u1`` trip 3 -- summed n_unweighted across every NAMED purpose at position "later"
      is 1, not 2) but MUST appear in the pooled ``purpose == "all"`` cell (segment "employed"
      position "later" purpose "all" has n_unweighted == 2: the unknown trip plus the home trip).
    * Activity duration: ``u1`` trip 1 (work, arr 500) -> next dep 600 -> 1.667 h ("1-2h"),
      NAMED purpose "work". ``u1`` trip 2 (unknown, arr 620) -> next dep 650 -> 0.5 h ("0-0.5h"),
      MEASURABLE and in-range, so it is EXCLUDED from every named-purpose duration cell but
      INCLUDED in the pooled purpose "all" cell for segment "employed" (2 legs: work + unknown,
      weight 1.0 each -> "1-2h" share 0.5, "0-0.5h" share 0.5). ``u1`` trip 3 (home) and ``u2``
      trip 1 (shop) both have no following trip -> excluded, "no next".
    """
    persons = pd.DataFrame({
        "pid": ["u1", "u2"],
        "weight": [1.0, 1.0],
        "group": ["employed", "employed"],
    })
    trips = pd.DataFrame({
        "pid":          ["u1", "u1", "u1", "u2"],
        "seq":          [1, 2, 3, 1],
        "weight":       [1.0, 1.0, 1.0, 1.0],
        "purpose":      ["work", SRV.UNKNOWN_PURPOSE, "home", "shop"],
        "prev_purpose": ["home", "work", SRV.UNKNOWN_PURPOSE, "home"],
        "dep_min":      [480.0, 600.0, 650.0, 500.0],
        "arr_min":      [500.0, 620.0, 670.0, 520.0],
    })
    return persons, trips


def _n_unweighted(table: pd.DataFrame, segment: str, purpose: str, position: str) -> int:
    """The (repeated) n_unweighted value of one departure-time cell (0 if the cell is absent,
    which should never happen now that the table is dense -- callers assert on this too)."""
    row = table[(table["segment"] == segment) & (table["purpose"] == purpose)
               & (table["position"] == position)]
    assert len(row) == T.N_BINS, "departure_time_table must be dense: expected %d rows, found %d" \
        % (T.N_BINS, len(row))
    values = row["n_unweighted"].unique()
    assert len(values) == 1, "n_unweighted must be constant within one cell, found %s" % values
    return int(values[0])


