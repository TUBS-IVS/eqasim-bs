def test_unknown_purpose_excluded_from_named_cells_and_pooled_under_all():
    persons, trips = _unknown_purpose_fixture()
    table = T.departure_time_table(persons, trips, np.random.RandomState(9))
    assert SRV.UNKNOWN_PURPOSE not in set(table["purpose"])
    # Only u1's home trip (later) is a NAMED-purpose "later" leg for segment "employed"; summed
    # across every named purpose it must be 1, while the pooled purpose "all" sees BOTH the
    # unknown-purpose leg and the home leg (n_unweighted 2).
    named_later_total = sum(_n_unweighted(table, "employed", purpose, "later")
                            for purpose in SRV.PURPOSES)
    assert named_later_total == 1
    assert _n_unweighted(table, "employed", T.PURPOSE_ALL, "later") == 2
    assert table.attrs["n_legs_unknown_purpose_raw"] == 1
    assert table.attrs["n_legs_unknown_purpose_valid_dep_min"] == 1


